"""
Build the hand-grade worksheet for a captured run.

For every op the grader FAILS, one block with everything a person needs to say
whose fault it is: the email as the model read it, the answer key with its
expected date already resolved (and the anchor it came from, and which earlier
email set it), the earlier emails the storyline depends on, everything the model
had on the calendar for that node that day, and the grader's own verdict. Then a
fixed random sample of PASSING ops, so the false-positive side is measured too.

    .venv/bin/python docs/_repair/audit_worksheet.py captures/baseline-sonnet-4-5 \
        > docs/_repair/audit-baseline-sonnet-4-5.md

Read-only: touches no corpus, capture or code. Register phase 1d.
"""
from __future__ import annotations

import glob
import json
import random
import sys
from datetime import date, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))   # repo root, so `sb` imports from anywhere

from sb import resolver  # noqa: E402
from sb.grader import keywords_of
from sb.live.runner import _grade_day, _node_state, _turn_delta
from sb.resolver import Context, Interval
from sb.schema import _predicate_exprs, _refs_in, load_corpus
from sb.scheduler import Levers, build_plan

CODES = """\
| code | meaning |
|---|---|
| **MODEL** | the answer key is right and the model did not do it, or did it wrong (missing, wrong day, wrong kind, duplicate, stale copy, not cancelled) |
| **KEY** | the answer key is wrong or the email does not support it: wrong date, wrong kind, no cue in the prose, an obligation nobody would infer |
| **PLAN** | the email was served after the date it talks about, so no answer could be right (register K-1) |
| **GRADER** | the model did the right thing and the grader still failed it |
| **AMBIGUOUS** | reasonable people would disagree |
"""


def fmt_value(v) -> str:
    if isinstance(v, Interval):
        return f"{v.start:%a %b %d} to {v.end:%a %b %d}"
    if isinstance(v, datetime):
        return f"{v:%a %b %d %Y %H:%M}"
    if isinstance(v, date):
        return f"{v:%a %b %d %Y}"
    return str(v)


def bare(name: str) -> str:
    return name.split("__", 2)[-1] if name.startswith("__obl_") else name


def main(capture: str, sample_passes: int = 15, seed: int = 42) -> None:
    man = json.loads(Path(capture, "manifest.json").read_text())
    corpus = load_corpus(man["corpus_dir"])
    lv = man["levers"]
    plan = build_plan(corpus, start_date=date.fromisoformat(man["start"]), seed=man["seed"],
                      n_days=man["n_days"],
                      levers=Levers(lv["daily_min"], lv["daily_max"], lv["urgency_horizon"]))
    days = [json.loads(Path(p).read_text()) for p in sorted(glob.glob(f"{capture}/days/*.json"))]
    day_of = {eid: rec for rec in days for eid in rec["batch"]}

    def ctx_for(eid):
        return Context(plan.serve_date[eid], plan.anchors)

    def body_of(eid):
        e = corpus.emails[eid]
        return resolver.render_body(e.body, ctx_for(eid)).text.strip()

    # grade every day exactly as the runner does
    verdicts = {}
    for rec in days:
        if rec.get("ok"):
            verdicts.update(_grade_day(corpus, plan, rec["batch"], rec["state"], set(rec["day_new"])))

    failing, passing = [], []
    for rec in days:
        for eid in rec["batch"]:
            res = verdicts.get(eid)
            if res is None:
                continue
            for oi, d in enumerate(res.details):
                (passing if d["passed"] else failing).append((eid, oi, d))
    rnd = random.Random(seed)
    sample = sorted(rnd.sample(passing, min(sample_passes, len(passing))),
                    key=lambda t: (plan.serve_date[t[0]], t[0], t[1]))

    out = []
    p = out.append
    p(f"# Hand-grade worksheet: `{capture}`\n")
    p(f"Model `{man.get('served_model') or man.get('requested_model')}`"
      f"{' (certified)' if man.get('model_certified') else ''}, corpus `{man['corpus_dir']}` sha "
      f"`{man.get('corpus_hash')}`, seed {man['seed']}, levers {lv}. Generated by "
      f"`docs/_repair/audit_worksheet.py`; the grader is the one in `sb/grader.py` at generation time.\n")
    p("Score under this grader: "
      f"**{sum(1 for r in verdicts.values() if r.passed)}/{len(verdicts)}** emails; "
      f"**{len(failing)}** failing ops, **{len(passing)}** passing ops (no-action emails count as one op).\n")
    p("## How to use this\n")
    p("Part A is every failing op. For each one, read the email, the key, and what the model had, then "
      "tick one code and write a line of notes. Part B is a random sample of passing ops: say whether "
      "you would have passed it. Do not look at the grader's reason until you have formed your own view; "
      "it is there so the two can be compared afterwards.\n")
    p(CODES)
    p("Things the worksheet resolves for you: **expected dates are already computed** from the serve plan, "
      "and each anchor a key refers to is listed with its value and the earlier email that set it. "
      "**Objects** are everything on the calendar for that node on that day: ★ created for this email, "
      "☆ created that day for a sibling email, no mark = inherited from an earlier day. Times are the "
      "model's; grading is whole-day. The raw corpus is in `corpus/nodes/<node>.json` if you need more "
      "of the storyline than the direct dependencies shown.\n")

    def block(n, eid, oi, d, passing_mode=False):
        e = corpus.emails[eid]
        rec = day_of[eid]
        sd = plan.serve_date[eid]
        op = e.answer.ops[oi] if e.answer.ops else None
        head = f"{op.verb} `{op.name}` ({op.kind})" if op else "no-action email"
        p(f"### {n}. `{eid}` · {head}\n")
        p(f"- **served** {sd:%a %b %d %Y} (day {rec['day']}) · **node** `{e.node}` · **from** {e.sender} · "
          f"**subject** {e.subject}")
        deps = e.depends_on
        if deps:
            p("- **depends on** " + "; ".join(
                f"`{x.email}` ({x.type}, served {plan.serve_date[x.email]:%b %d})" for x in deps))
        anc = corpus.ancestors(eid) - {x.email for x in deps}
        if anc:
            p("- **earlier in the storyline** " + ", ".join(
                f"`{a}`" for a in sorted(anc, key=lambda a: plan.serve_date[a])))
        p("\n**The email, as the model read it:**\n")
        p("> " + body_of(eid).replace("\n", "\n> ") + "\n")
        for x in deps:
            p(f"**Dependency `{x.email}`** (served {plan.serve_date[x.email]:%b %d}, subject: "
              f"{corpus.emails[x.email].subject}):\n")
            p("> " + body_of(x.email).replace("\n", "\n> ") + "\n")
        p("**Answer key for this op:**\n")
        if op:
            kw = ", ".join(sorted(keywords_of(op)))
            p(f"- `{op.verb}` **{op.name}** as a **{op.kind}**; identity words: `{kw}`")
            if op.on:
                p(f"- date predicate `{json.dumps(op.on)}` → **{d['expected']}**")
                for expr in _predicate_exprs(op.on):
                    for ref in sorted(_refs_in(expr)):
                        val = plan.anchors.get(ref)
                        src = corpus.emission_map.get(ref)
                        p(f"  - `@{bare(ref)}` = {fmt_value(val)}" + (f", set by `{src}`" if src else ""))
            else:
                p(f"- expected: {d['expected']}")
            others = [o for j, o in enumerate(e.answer.ops) if j != oi]
            if others:
                p("- other ops in this email: " + "; ".join(f"{o.verb} `{o.name}`" for o in others))
        else:
            p(f"- {d['expected']}")
        # objects
        state, day_new = rec["state"], set(rec["day_new"])
        by_eid = rec["by_eid"]
        mine = {i for i in day_new if by_eid.get(i) == eid}
        ns = _node_state(corpus, state, e.node, mine)
        mine_keys = {(o.kind, o.title, o.when, o.email_id) for o in
                     (_turn_delta(corpus, state, mine).events + _turn_delta(corpus, state, mine).todos)}
        today = _turn_delta(corpus, state, day_new)
        today_keys = {(o.kind, o.title, o.when, o.email_id) for o in today.events + today.todos}
        objs = sorted(ns.events + ns.todos, key=lambda o: (o.when, o.kind, o.title))
        p(f"\n**What the model had for `{e.node}` on {sd:%b %d}** ({len(objs)} objects):\n")
        if objs:
            p("| | kind | title | when | description | stamped to |")
            p("|---|---|---|---|---|---|")
            for o in objs:
                k = (o.kind, o.title, o.when, o.email_id)
                mark = "★" if k in mine_keys else ("☆" if k in today_keys else "")
                desc = (o.description or "").replace("|", "\\|").replace("\n", " ")
                p(f"| {mark} | {o.kind} | {o.title.replace('|', chr(92) + '|')} | {o.when:%a %b %d %H:%M} | {desc} | `{o.email_id}` |")
        else:
            p("_(nothing)_")
        said = (rec.get("said") or "").strip().replace("\n", " ")
        if said:
            p(f"\n**Model's narration that day** (all emails of the day): {said[:400]}{'…' if len(said) > 400 else ''}")
        p(f"\n**Grader's verdict:** {'PASS' if d['passed'] else 'FAIL'} — {d['reason']}  \n"
          f"**Grader's `actual`:** {d['actual']}\n")
        if passing_mode:
            p("**Would you have passed it?** `[ ]` YES   `[ ]` NO   `[ ]` AMBIGUOUS  \n**Notes:** \n")
        else:
            p("**Your verdict:** `[ ]` MODEL   `[ ]` KEY   `[ ]` PLAN   `[ ]` GRADER   `[ ]` AMBIGUOUS  \n"
              "**Notes:** \n")
        p("---\n")

    p(f"\n## Part A — the {len(failing)} failing ops\n")
    for n, (eid, oi, d) in enumerate(failing, 1):
        block(n, eid, oi, d)
    p(f"\n## Part B — {len(sample)} passing ops, sampled (seed {seed})\n")
    p("A grader that never fails a correct answer can still pass wrong ones. Same blocks; say whether "
      "you agree with the pass.\n")
    for n, (eid, oi, d) in enumerate(sample, 1):
        block(f"B{n}", eid, oi, d, passing_mode=True)
    p("\n## Tally (fill in when done)\n")
    p("| code | count |\n|---|---|\n| MODEL | |\n| KEY | |\n| PLAN | |\n| GRADER | |\n| AMBIGUOUS | |\n"
      "| Part B: would NOT have passed | |\n")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "captures/baseline-sonnet-4-5")
